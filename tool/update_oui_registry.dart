import 'dart:convert';
import 'dart:io';

final _sources = <String, ({int prefixLength, Uri uri})>{
  'MA-L': (
    prefixLength: 24,
    uri: Uri.parse('https://standards-oui.ieee.org/oui/oui.csv'),
  ),
  'MA-M': (
    prefixLength: 28,
    uri: Uri.parse('https://standards-oui.ieee.org/oui28/mam.csv'),
  ),
  'MA-S': (
    prefixLength: 36,
    uri: Uri.parse('https://standards-oui.ieee.org/oui36/oui36.csv'),
  ),
  'IAB': (
    prefixLength: 36,
    uri: Uri.parse('https://standards-oui.ieee.org/iab/iab.csv'),
  ),
};

Future<void> main() async {
  final client = HttpClient()..userAgent = 'SpyDevDet OUI updater/1.0';
  final entries = <String, _OuiEntry>{};
  try {
    for (final source in _sources.entries) {
      final request = await client.getUrl(source.value.uri);
      request.headers.set(HttpHeaders.acceptHeader, 'text/csv');
      final response = await request.close();
      if (response.statusCode != HttpStatus.ok) {
        throw HttpException(
          'IEEE ${source.key} listesi indirilemedi: ${response.statusCode}',
          uri: source.value.uri,
        );
      }
      final csv = await utf8.decoder.bind(response).join();
      for (final line in const LineSplitter().convert(csv).skip(1)) {
        final columns = _parseCsvLine(line);
        if (columns.length < 3) {
          continue;
        }
        final assignment = columns[1]
            .replaceAll(RegExp('[^0-9A-Fa-f]'), '')
            .toUpperCase();
        final expectedLength = (source.value.prefixLength / 4).ceil();
        final organization = _normalize(columns[2]);
        if (assignment.length != expectedLength || organization.isEmpty) {
          continue;
        }
        entries['${source.value.prefixLength}|$assignment'] = _OuiEntry(
          prefixLength: source.value.prefixLength,
          assignment: assignment,
          organization: organization,
        );
      }
    }

    final sorted = entries.values.toList()
      ..sort((first, second) {
        final byLength = second.prefixLength.compareTo(first.prefixLength);
        return byLength != 0
            ? byLength
            : first.assignment.compareTo(second.assignment);
      });
    if (sorted.length < 1000) {
      throw StateError('Beklenenden az IEEE kaydı bulundu: ${sorted.length}');
    }

    final output = File('assets/data/oui_registry.tsv');
    await output.parent.create(recursive: true);
    final buffer = StringBuffer()
      ..writeln('# Generated by tool/update_oui_registry.dart')
      ..writeln(
        '# Source: https://standards.ieee.org/products-programs/regauth/',
      )
      ..writeln('# Updated: ${DateTime.now().toUtc().toIso8601String()}')
      ..writeln('# Fields: prefixLength\\tassignment\\torganization');
    for (final entry in sorted) {
      buffer.writeln(
        '${entry.prefixLength}\t${entry.assignment}\t${entry.organization}',
      );
    }
    await output.writeAsString(buffer.toString(), flush: true);
    stdout.writeln(
      '${sorted.length} IEEE kaydı ${output.path} dosyasına yazıldı.',
    );
  } finally {
    client.close(force: true);
  }
}

List<String> _parseCsvLine(String line) {
  final fields = <String>[];
  final field = StringBuffer();
  var quoted = false;
  for (var index = 0; index < line.length; index++) {
    final character = line[index];
    if (character == '"') {
      if (quoted && index + 1 < line.length && line[index + 1] == '"') {
        field.write('"');
        index++;
      } else {
        quoted = !quoted;
      }
    } else if (character == ',' && !quoted) {
      fields.add(field.toString());
      field.clear();
    } else {
      field.write(character);
    }
  }
  fields.add(field.toString());
  return fields;
}

String _normalize(String value) => value
    .replaceAll(RegExp(r'[\t\r\n]+'), ' ')
    .replaceAll(RegExp(r'\s{2,}'), ' ')
    .trim();

class _OuiEntry {
  const _OuiEntry({
    required this.prefixLength,
    required this.assignment,
    required this.organization,
  });

  final int prefixLength;
  final String assignment;
  final String organization;
}
